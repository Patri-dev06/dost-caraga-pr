<?php

namespace App\Documents;

use App\Models\PurchaseRequest;
use App\Models\User;
use TCPDF;

/**
 * The Purchase Request form (GPPB Appendix 60) as a PDF for PNPKI digital signing, built from the
 * PR's saved data. It also returns where each signatory's signature goes — "requested",
 * "recommending" and "approving" — in PDF points, for the signing helper.
 */
class PurchaseRequestPdf
{
    public const ENTITY_NAME = 'DEPARTMENT OF SCIENCE AND TECHNOLOGY - CARAGA';

    private const FONT = 'dejavuserif';

    private const MARGIN = 12.0; // mm

    private const PAGE_HEIGHT = 297.0; // A4, mm

    /**
     * @return array{pdf: string, fields: list<array{name: string, label: string, page: int, box: array{0: float, 1: float, 2: float, 3: float}}>}
     */
    public static function build(PurchaseRequest $pr, ?User $regionalDirector): array
    {
        $pr->loadMissing(['office', 'fundSource', 'project', 'items', 'requester', 'recommendingOfficer']);

        $pdf = new TCPDF('P', 'mm', 'A4', true, 'UTF-8');
        $pdf->setCreator('DOST Caraga Procurement System');
        $pdf->setAuthor(self::ENTITY_NAME);
        $pdf->setTitle("Purchase Request {$pr->pr_no}");
        $pdf->setPrintHeader(false);
        $pdf->setPrintFooter(false);
        $pdf->setMargins(self::MARGIN, self::MARGIN, self::MARGIN);
        $pdf->setAutoPageBreak(true, self::MARGIN + 6);
        $pdf->AddPage();
        $pdf->SetFont(self::FONT, '', 9);

        $pdf->writeHTML(self::formHtml($pr), true, false, true, false, '');

        $fields = self::signatureBlock($pdf, $pr, $regionalDirector);

        // A small line under the form saying where the PDF came from.
        $pdf->SetFont(self::FONT, 'I', 6.5);
        $pdf->SetTextColor(110, 110, 110);
        $pdf->Cell(0, 5, "Generated by the DOST Caraga Procurement System for PNPKI digital signing · PR No. {$pr->pr_no}", 0, 1, 'L');

        return ['pdf' => $pdf->Output('', 'S'), 'fields' => $fields];
    }

    private static function formHtml(PurchaseRequest $pr): string
    {
        $e = fn (?string $value): string => nl2br(htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8'));
        $money = fn (float $value): string => number_format($value, 2);
        $date = ($pr->submitted_at ?? $pr->created_at)?->timezone(config('app.timezone', 'Asia/Manila'))->format('F j, Y') ?? '';
        $chargedTo = trim(($pr->fundSource?->name ?? '').($pr->project?->title ? ' · '.$pr->project->title : ''));

        $rows = '';
        $total = 0.0;
        foreach ($pr->items as $item) {
            $lineTotal = (float) $item->quantity * (float) $item->unit_cost;
            $total += $lineTotal;
            $description = $item->name.($item->description ? "\n".$item->description : '');
            $rows .= '<tr>'
                .'<td width="11%"></td>'
                .'<td width="9%" align="center">'.$e($item->uom).'</td>'
                .'<td width="44%">'.$e($description).'</td>'
                .'<td width="10%" align="center">'.rtrim(rtrim(number_format((float) $item->quantity, 2), '0'), '.').'</td>'
                .'<td width="12%" align="right">'.$money((float) $item->unit_cost).'</td>'
                .'<td width="14%" align="right">'.$money($lineTotal).'</td>'
                .'</tr>';
        }

        return <<<HTML
<p align="center" style="font-size:13pt;font-weight:bold;">PURCHASE REQUEST</p>
<table border="1" cellpadding="3">
  <tr>
    <td width="66%" colspan="2"><b>Entity Name:</b> {$e(self::ENTITY_NAME)}</td>
    <td width="34%"><b>Fund Cluster:</b> 01</td>
  </tr>
  <tr>
    <td width="33%"><b>Office/Section:</b><br/>{$e($pr->office?->name)}</td>
    <td width="33%"><b>PR No.:</b> {$e($pr->pr_no)}<br/><b>Responsibility Center Code:</b></td>
    <td width="34%"><b>Date:</b> {$e($date)}</td>
  </tr>
</table>
<table border="1" cellpadding="3">
  <thead>
    <tr style="font-weight:bold;" align="center">
      <th width="11%">Stock/ Property No.</th>
      <th width="9%">Unit</th>
      <th width="44%">Item Description</th>
      <th width="10%">Quantity</th>
      <th width="12%">Unit Cost</th>
      <th width="14%">Total Cost</th>
    </tr>
  </thead>
  {$rows}
  <tr>
    <td width="74%" colspan="4"></td>
    <td width="12%" align="right"><b>TOTAL</b></td>
    <td width="14%" align="right"><b>{$money($total)}</b></td>
  </tr>
</table>
<table border="1" cellpadding="3">
  <tr>
    <td width="100%"><b>Purpose:</b> {$e($pr->purpose)}<br/><b>Charged to:</b> <i>{$e($chargedTo)}</i></td>
  </tr>
</table>
HTML;
    }

    /**
     * Requested by / Recommending Approval / Approved by, kept together on one page. The Signature
     * row is left empty: each signatory's digital signature is drawn there when they sign.
     *
     * @return list<array{name: string, label: string, page: int, box: array{0: float, 1: float, 2: float, 3: float}}>
     */
    private static function signatureBlock(TCPDF $pdf, PurchaseRequest $pr, ?User $regionalDirector): array
    {
        $labelWidth = 26.0;
        $column = (210.0 - 2 * self::MARGIN - $labelWidth) / 3;
        $heights = ['head' => 6.0, 'sign' => 26.0, 'name' => 6.0, 'designation' => 6.0];
        $blockHeight = array_sum($heights);

        if ($pdf->GetY() + $blockHeight > self::PAGE_HEIGHT - self::MARGIN - 8) {
            $pdf->AddPage();
        }
        $top = $pdf->GetY();
        $x = self::MARGIN;

        $signatories = [
            ['requested', 'Requested by:', $pr->requester?->name, $pr->requester?->position],
            ['recommending', 'Recommending Approval:', $pr->recommendingOfficer?->name, $pr->recommending_designation ?: $pr->recommendingOfficer?->position],
            ['approving', 'Approved by:', $regionalDirector?->name, $pr->approving_designation ?: 'Regional Director'],
        ];

        $pdf->SetFont(self::FONT, '', 8.5);
        $pdf->SetTextColor(0, 0, 0);
        $rows = [['head', ''], ['sign', 'Signature:'], ['name', 'Printed Name:'], ['designation', 'Designation:']];
        $y = $top;
        foreach ($rows as [$row, $label]) {
            $height = $heights[$row];
            $pdf->SetXY($x, $y);
            $pdf->Cell($labelWidth, $height, $label, 1, 0, 'L');
            foreach ($signatories as [$_name, $heading, $printedName, $designation]) {
                $text = match ($row) {
                    'head' => $heading,
                    'name' => mb_strtoupper((string) $printedName),
                    'designation' => (string) $designation,
                    default => '',
                };
                $pdf->SetFont(self::FONT, $row === 'name' ? 'B' : '', $row === 'name' ? 8.5 : 8);
                $pdf->Cell($column, $height, $text, 1, 0, $row === 'head' ? 'L' : 'C', false, '', 1);
            }
            $pdf->SetFont(self::FONT, '', 8.5);
            $y += $height;
        }
        $pdf->SetXY($x, $y + 1);

        // Each signature box (the Signature row's cell, inset 1 mm) in PDF points from the bottom-left.
        $points = fn (float $mm): float => round($mm * 72 / 25.4, 2);
        $signTop = $top + $heights['head'];
        $page = $pdf->getPage() - 1;
        $fields = [];
        foreach ($signatories as $i => [$name, $heading]) {
            $left = $x + $labelWidth + $i * $column;
            $fields[] = [
                'name' => $name,
                'label' => rtrim($heading, ':'),
                'page' => $page,
                'box' => [
                    $points($left + 1),
                    $points(self::PAGE_HEIGHT - ($signTop + $heights['sign'] - 1)),
                    $points($left + $column - 1),
                    $points(self::PAGE_HEIGHT - ($signTop + 1)),
                ],
            ];
        }

        return $fields;
    }
}
